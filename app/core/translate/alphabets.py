# -*- coding: utf-8 -*-
"""Алфавиты-словари: отдельные знаки каны, кириллицы и латиницы.

Переводчики (NLLB, Google, LLM) галлюцинируют на одиночных знаках:
«ホ» → «Домой», «C» → «В)». Одиночная буква — не слово: это кнопки
кана-клавиатуры (ホ, ァ…), хоткеи (A, Б), междометия одного знака.
Такой знак перевода не имеет и возвращается как есть — движку
не отправляется ни в одном провайдере и ни в одном режиме.
"""
from __future__ import annotations

import re

# японская кана: хирагана, катакана, фонетические расширения, полушириная
KANA = r"\u3040-\u30FF\u31F0-\u31FF\uFF65-\uFF9F"
# кириллица (включая ё и буквы расширенной кириллицы)
CYRILLIC = r"\u0400-\u04FF"
# латиница
LATIN = r"A-Za-z"

SINGLE_LETTER_RE = re.compile(rf"^[{KANA}{CYRILLIC}{LATIN}]$")


def is_single_letter(text: str) -> bool:
    """True, если строка — ровно один знак каны/кириллицы/латиницы."""
    return bool(SINGLE_LETTER_RE.match(text.strip()))
